import assert from 'node:assert/strict';
import fs from 'node:fs';
import {normalizePlan,initialState,planned,metrics,addActivity,linkActivity,readiness,nutrition,weeklySeries,analysisActivities,weeklyReport} from './engine.mjs';
const plan=normalizePlan(JSON.parse(fs.readFileSync(new URL('./plan-semana.json',import.meta.url),'utf8')));
assert.equal(planned(plan),335);
assert.equal(plan.sessions.length,6);
assert.throws(()=>normalizePlan({...plan,week_start:'2026-11-03'}));
assert.throws(()=>normalizePlan({...plan,sessions:[plan.sessions[0],plan.sessions[0]]}));
const st=initialState();st.plans[plan.week_start]=plan;
assert.equal(metrics(st,plan.week_start).scheduled,335);
st.logs[plan.sessions[0].id]={done:true,minutes:30,rpe:3};
assert.equal(analysisActivities(st).length,1);
let raw={id:'activity-1',source:'import',date:'2026-11-02',sport:'run',minutes:30,distanceKm:5,hr:133,power:null,rpe:3,title:'Rodaje'};
assert.equal(addActivity(st,raw),true);
assert.equal(addActivity(st,raw),false);
linkActivity(st,'activity-1','nov02-run');
assert.equal(analysisActivities(st).length,1);
assert.equal(metrics(st,plan.week_start).completed,30);
assert.equal(metrics(st,plan.week_start).extra,0);
assert.equal(weeklyReport(st,plan.week_start).sports.find(x=>x.sport==='run').sessions,1);
const r=readiness({...st,wellness:{'2026-11-02':{sleep:5.2,stress:4,fatigue:5,pain:0}}},'2026-11-02');assert.equal(r.level,'reduce');
assert.equal(readiness(st,'2026-11-02').level,'unknown');
assert.equal(nutrition(null,2100,'bike',60),null);
const n=nutrition(70,2100,'bike',60);assert(n?.kcal>2100&&n.protein>90&&n.carbs>100);
const series=weeklySeries(analysisActivities(st),'2026-11-02','run','pace');assert(series.at(-1).value!==null);
console.log('OK 15+ comprobaciones de motor y formato.');
